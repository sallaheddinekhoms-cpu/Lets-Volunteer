    try:
        import dj_database_url
        DATABASES = {
            "default": dj_database_url.config(
                default=DATABASE_URL,
                conn_max_age=600,
                conn_health_checks=True,
            )
        }
    except Exception:
        import urllib.parse
        parsed = urllib.parse.urlparse(DATABASE_URL)
        engine = "django.db.backends.postgresql" if "postgres" in parsed.scheme else "django.db.backends.mysql"
        DATABASES = {
            "default": {
                "ENGINE": engine,
                "NAME": parsed.path.lstrip("/"),
                "USER": parsed.username or "",
                "PASSWORD": parsed.password or "",
                "HOST": parsed.hostname or "",
                "PORT": str(parsed.port or (5432 if "postgres" in parsed.scheme else 3306)),
            }
        }
